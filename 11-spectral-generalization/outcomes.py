def table(frame):
    cols=list(frame.columns)
    lines=["| "+" | ".join(cols)+" |","|"+"---|"*len(cols)]
    for row in frame.itertuples(index=False,name=None):
        lines.append("| "+" | ".join("not reported" if pd.isna(v) else
            f"{v:.4f}" if isinstance(v,float) else str(v) for v in row)+" |")
    return "\n".join(lines)


